import { defineConfig } from "vitest/config";
import react from "@vitejs/plugin-react";
import { realpathSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { searchForWorkspaceRoot } from "vite";

const projectRoot = dirname(fileURLToPath(import.meta.url));

export default defineConfig({
  plugins: [react()],
  // Worktrees may symlink node_modules to the primary checkout. Vite's test
  // asset loader needs access to that real path for self-hosted font URLs.
  server: { fs: { allow: [searchForWorkspaceRoot(projectRoot), realpathSync(resolve(projectRoot, "node_modules"))] } },
  assetsInclude: ["**/*.md"],
  build: {
    rollupOptions: {
      output: {
        /**
         * Keep the Supabase SDK out of the entry chunk. It is the largest
         * dependency in the app (~838 KB of source across auth, postgrest,
         * storage, realtime and phoenix) and it changes only when the SDK is
         * upgraded, so bundling it with app code means every deploy
         * invalidates it in visitors' caches.
         *
         * This splits it, it does not defer it: the landing page's event list
         * needs Supabase, so the chunk is still fetched on load — in parallel
         * with the entry rather than inside it. Actually deferring it needs an
         * async client accessor across all 39 importers; see the note in
         * src/lib/supabase.ts.
         */
        manualChunks(id: string): string | undefined {
          if (id.includes("node_modules/@supabase/")) return "supabase";
          return undefined;
        },
      },
    },
  },
  test: {
    globals: true,
    environment: "jsdom",
    setupFiles: "./src/test/setup.ts",
    exclude: [
      "**/node_modules/**",
      "**/dist/**",
      // Agent-tooling directories: not app code, and their tests use Node's
      // built-in node:test runner, which vitest can't bundle.
      ".claude/**",
      ".agents/**",
      // Design-system handoff sync target: regenerated by the design tool,
      // never imported by src/, never built. Its bundled *.test.tsx files
      // reference paths relative to their original project layout, so
      // collecting them here fails import resolution.
      ".design-sync/**",
      // Local git worktrees: each is an independent checkout with its own
      // src/ tree. Vitest would collect their test files alongside the
      // main checkout and run them against THIS tree's node_modules,
      // producing misleading failures.
      ".worktrees/**",
      // Supabase Edge Functions: Deno runtime code and tests (import from
      // https:// specifiers, e.g. deno.land/std, and reference the global
      // `Deno` object). Not Node/Vite-bundleable — run these with
      // `deno test`, not vitest. Matched at any depth so nested worktrees
      // under .worktrees/ are covered too.
      "**/supabase/functions/**",
    ],
  },
});
